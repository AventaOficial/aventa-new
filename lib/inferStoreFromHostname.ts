export function inferStoreFromHostname(hostname: string): string | null {
  const h = hostname.replace(/^www\./, '').toLowerCase();
  if (!h) return null;
  for (const { suffix, store } of SUFFIX_TO_STORE) {
    if (h === suffix || h.endsWith(`.${suffix}`)) return store;
  }
  return null;
}
